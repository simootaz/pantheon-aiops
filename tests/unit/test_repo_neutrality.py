def test_no_attribution_in_tracked_paths() -> None:
    """No tracked file is named after an assistant tool."""
    offenders = [
        f"{path.relative_to(REPO_ROOT)} -> {reasons}"
        for path in _tracked_files()
        if (reasons := _violations(path.as_posix()))
    ]
    assert not offenders, f"tracked paths claiming AI authorship: {offenders}"


def test_no_attribution_in_tracked_contents() -> None:
    """No tracked file attributes its authorship to an assistant."""
    offenders: list[str] = []

    for path in _tracked_files():
        if path.resolve() == SELF or not path.is_file():
            continue
        text = read_scannable(path)
        if reasons := _violations(text):
            offenders.append(f"{path.relative_to(REPO_ROOT)} -> {reasons}")

    assert not offenders, "tracked files claiming AI authorship:\n  " + "\n  ".join(offenders)


def test_repository_map_is_tracked_and_canonical() -> None:
    """docs/REPOSITORY_MAP.md is the committed map, and it is substantial.

    A neutralisation that quietly dropped the map instead of moving it would
    pass the tests above while destroying the thing they protect.
    """
    tracked = {path.relative_to(REPO_ROOT).as_posix() for path in _tracked_files()}
    assert "docs/REPOSITORY_MAP.md" in tracked

    body = read_verbatim(
        REPO_ROOT / "docs" / "REPOSITORY_MAP.md",
        why="Markdown headings start with # and would be stripped",
    )
    for heading in (
        "## Project identity",
        "## Language boundaries",
        "## Folder map",
        "## Where do I put X?",
        "## Generated files",
        "## Standing decisions",
        "## Git Flow rules",
        "## Commands",
        "## Phase roadmap",
        "## Structure changelog",
    ):
        assert heading in body, f"repository map is missing section: {heading}"
