def test_guard_permits_provider_documentation() -> None:
    """Vendor names, model ids and API hosts are product content, not attribution.

    This test exists to stop the guard being re-broadened into a vendor-substring
    ban. If it starts failing, the guard has drifted - fix the guard, not this
    test.
    """
    sample = """
    | Provider     | Dialect           | Example model          |
    |--------------|-------------------|------------------------|
    | OpenRouter   | chat_completions  | openai/gpt-4o-mini     |
    | Groq         | chat_completions  | llama-3.3-70b-versatile|
    | Anthropic    | messages          | claude-sonnet-4        |
    | Google       | generate_content  | gemini-2.0-flash       |
    | DeepSeek     | chat_completions  | deepseek-chat          |
    | Ollama       | chat_completions  | qwen2.5:14b            |

    Endpoints: https://api.anthropic.com/v1/messages,
               https://api.openai.com/v1/chat/completions
    Set PANTHEON_LLM_MODEL=claude-sonnet-4 to pin the frontier tier.
    """
    assert _violations(sample) == []


def test_guard_catches_authorship_attribution() -> None:
    """The patterns that matter are still caught."""
    cases = (
        "Co-Authored-By: Claude <noreply@example.com>",
        "Generated with Claude Code",
        "This module was written by an AI assistant.",
        "\N{ROBOT FACE} generated",
        "See CLAUDE.md for the repository map",
        "config lives in .claude/settings.json",
    )
    for case in cases:
        assert _violations(case), f"guard failed to catch: {case!r}"


