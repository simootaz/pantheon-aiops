"""Guards that the public repository claims no AI authorship.

The repository is public. Which local tools a contributor happens to use is
their business and must not be recorded in tracked files. See
docs/adr/0003-neutral-repository-documentation.md.

## What is banned: attribution, not vendors

This guard matches *authorship attribution patterns* - a co-author trailer
naming an assistant, a "generated by" footer, an emoji sign-off, a reference to
an assistant's local pointer file or config directory.

It deliberately does **not** ban vendor names, model identifiers or API hosts.
Those are product functionality: Pantheon is an LLM platform, so its docs and
config legitimately name providers, list example models and document dialects -
exactly as ADR 0001 names MinIO, S3 and Ceph. Nobody infers AI authorship from a
supported-providers table; every tool in this space ships one.

An earlier version banned vendor substrings outright. That was the wrong shape:
it blocked legitimate product content while catching nothing extra, since
attribution is a phrase, not a word.

`test_guard_permits_provider_documentation` pins that distinction so the rule
cannot be quietly re-broadened.

Scope: *tracked* files only, via `git ls-files`. Untracked and gitignored files
are deliberately out of scope - local pointer files are permitted precisely
because they never enter the repository. Commit messages are not checked here;
see the ADR.

Phase: 0 - Scaffold & Tooling
"""

from __future__ import annotations

import re
import subprocess
from pathlib import Path

from tests.mechanism import read_scannable, read_verbatim

REPO_ROOT = Path(__file__).resolve().parents[2]

# Names that identify an AI coding assistant rather than a model vendor. Used
# only as the object of an attribution phrase, never on its own.
_ASSISTANT = (
    r"(?:claude\s*code|claude|chatgpt|gpt-[0-9]|copilot|codex|cursor|"
    r"an?\s+ai|ai\s+(?:assistant|agent|model))"
)

# (pattern, human-readable reason). Matched case-insensitively.
ATTRIBUTION_PATTERNS: tuple[tuple[str, str], ...] = (
    (rf"co-authored-by:[^\n]*{_ASSISTANT}", "co-author trailer naming an assistant"),
    (
        rf"(?:generated|created|written|authored|produced)\s+(?:with|by)\s+[^\n]{{0,40}}?{_ASSISTANT}",
        "authorship attributed to an assistant",
    ),
    (r"\N{ROBOT FACE}", "robot-emoji sign-off"),
    (r"claude\.md", "assistant pointer filename"),
    (r"(?<![\w.-])\.claude/", "assistant config directory"),
)

_COMPILED = tuple((re.compile(p, re.IGNORECASE), why) for p, why in ATTRIBUTION_PATTERNS)

# This scanner necessarily spells the patterns out, so it excludes itself.
# Every other tracked file is scanned.
SELF = Path(__file__).resolve()


def _violations(text: str) -> list[str]:
    """Return a reason for each attribution pattern present in text."""
    return [why for pattern, why in _COMPILED if pattern.search(text)]


def _tracked_files() -> list[Path]:
    """Every file git tracks, as absolute paths."""
    result = subprocess.run(
        ["git", "ls-files", "-z"],
        cwd=REPO_ROOT,
        capture_output=True,
        check=True,
        text=True,
    )
    return [REPO_ROOT / name for name in result.stdout.split("\0") if name and name.strip()]


